import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../../shared/', import.meta.url);
async function sources(dir) {
    const result = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        const url = new URL(entry.name + (entry.isDirectory() ? '/' : ''), dir);
        if (entry.isDirectory()) result.push(...await sources(url));
        else if (entry.name.endsWith('.js') && !entry.name.endsWith('.test.js') && entry.name !== 'ContentContract.js') result.push(url);
    }
    return result;
}
const hash = createHash('sha256');
for (const url of (await sources(root)).sort((a,b)=>a.href < b.href ? -1 : 1)) {
    hash.update(url.href.slice(root.href.length)); hash.update(await readFile(url));
}
const output = `// Generated by tools/net/content-contract.mjs; shared rules and map assets must agree.\nexport const CONTENT_CONTRACT = Object.freeze({ protocol: 2, content: '${hash.digest('hex')}' });\n`;
const target = new URL('session/ContentContract.js', root);
if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw Error('Content contract is stale; run node tools/net/content-contract.mjs and rebuild clients.');
} else await writeFile(target, output);
