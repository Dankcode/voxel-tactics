#!/usr/bin/env node
// PLAN-15: bake the real-place profiles the theme generator samples (heights by use, footprint depth ratios).
// Run after adding or re-importing a place:  node tools/geo/place-profiles.mjs   (npm run geo:profiles)
// Themes: each catalog place feeds the generator family named in THEME_FAMILY (by the place's theme).
import { writeFileSync } from 'node:fs';
import { GEO_MAPS } from '../../shared/mission/generated/GeoCatalog.js';
import { bakedProfiles } from '../../shared/mapgen/geo/PlaceProfiles.source.js';

const out = bakedProfiles(GEO_MAPS);
const file = new URL('../../shared/mapgen/geo/PlaceProfiles.generated.js', import.meta.url);
writeFileSync(file, `// GENERATED by tools/geo/place-profiles.mjs from the geo catalog — do not edit by hand.\n// Real-place statistics per generator family (PLAN-15): storey counts by use and footprint depth ratios.\nexport const PLACE_PROFILES = Object.freeze(${JSON.stringify(out, null, 1)});\n`);
console.log(Object.entries(out).map(([f, p]) => `${f}: ${p.places.join(', ')} · ${p.ratios.length} footprints · ${Object.values(p.all).reduce((a, b) => a + b, 0)} heights`).join('\n'));
